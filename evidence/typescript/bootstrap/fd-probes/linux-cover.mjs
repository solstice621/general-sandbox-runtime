import fs from 'node:fs';
import {spawnSync} from 'node:child_process';
const covered=process.argv[2]==='cover';
const source=Number(process.argv[3]);
const identity=fd=>{const s=fs.fstatSync(fd,{bigint:true});return {fd,dev:s.dev.toString(),ino:s.ino.toString()}};
const before=[identity(25),identity(192),identity(source)];
const nullFd=fs.openSync('/dev/null','r+');
const observed=fs.readdirSync('/proc/self/fd').filter(x=>/^\d+$/.test(x)).map(Number);
const max=Math.max(64,...observed);
const stdio=Array.from({length:covered?max+1:65},(_,i)=>i<3?(i===0?'ignore':'pipe'):(covered?nullFd:'ignore'));
stdio[64]=source;
const code=`import os,json\nout=[]\nfor fd in range(300):\n try:\n  s=os.fstat(fd);out.append(dict(fd=fd,dev=str(s.st_dev),ino=str(s.st_ino)))\n except OSError: pass\nos.write(64,b'grant-ok')\nprint(json.dumps(out))`;
const p=spawnSync('/usr/bin/python3',['-c',code],{stdio,encoding:'utf8'});
const after=[identity(25),identity(192),identity(source)];
console.log(JSON.stringify({covered,observedMax:max,before,after,child:p.stdout?JSON.parse(p.stdout):null,status:p.status,error:p.error?.message,stderr:p.stderr}));
